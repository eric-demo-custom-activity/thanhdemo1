/*
 * Runtime key builder (shared by browser and server).
 *
 * Deterministic, one-to-one mapping from a template target to a flat
 * inArguments key. The same function runs in the activity saver and in the
 * server validation, so both sides always agree on the key names.
 *
 *   addresses.phone              -> address__phone
 *   customerId  (recipient)      -> recipient__customerId
 *   params.customerName          -> param__customerName
 *
 * Fixed keys describe the activity itself and are never generated from a template:
 *   source, channel, templateKey, templateVersion, eventDefinitionKey
 */

import { listMappingTargets } from '../domain/mappingTargets.js';

export const FIXED_RUNTIME_KEYS = Object.freeze([
  'source',
  'channel',
  'templateKey',
  'templateVersion',
  'eventDefinitionKey',
]);

const GROUP_PREFIX = Object.freeze({
  addresses: 'address',
  recipientFields: 'recipient',
  params: 'param',
});

/**
 * Template target names: letters and digits, with single underscores between
 * segments. "__" is reserved as the separator, so it is forbidden in names.
 */
const SAFE_TARGET_NAME = /^[A-Za-z][A-Za-z0-9]*(_[A-Za-z0-9]+)*$/;

export class RuntimeKeyError extends Error {
  /**
   * @param {string} message
   * @param {string} code
   */
  constructor(message, code) {
    super(message);
    this.name = 'RuntimeKeyError';
    this.code = code;
  }
}

/**
 * @param {string} groupId - addresses | recipientFields | params
 * @param {string} name - template target name
 * @returns {string} the flat runtime key
 * @throws {RuntimeKeyError} when the name cannot be used safely
 */
export function runtimeKeyFor(groupId, name) {
  const prefix = GROUP_PREFIX[groupId];
  if (!prefix) {
    throw new RuntimeKeyError(`Unknown target group: ${groupId}`, 'UNKNOWN_GROUP');
  }
  if (typeof name !== 'string' || !SAFE_TARGET_NAME.test(name)) {
    throw new RuntimeKeyError(`Unsafe target name: ${String(name)}`, 'UNSAFE_TARGET_NAME');
  }
  return `${prefix}__${name}`;
}

/**
 * Builds the key map for every target of a template.
 *
 * @param {object|null} template
 * @returns {{ ok: true, keys: Record<string, string> } | { ok: false, errors: Array<{ code: string, message: string, targetKey: string }> }}
 */
export function buildRuntimeKeyMap(template) {
  const keys = {};
  const errors = [];
  const seen = new Map();

  for (const target of listMappingTargets(template)) {
    try {
      const key = runtimeKeyFor(target.groupId, target.name);
      if (FIXED_RUNTIME_KEYS.includes(key)) {
        errors.push({ code: 'RUNTIME_KEY_RESERVED', targetKey: target.key, message: `Key ${key} is reserved.` });
        continue;
      }
      if (seen.has(key)) {
        errors.push({
          code: 'RUNTIME_KEY_DUPLICATE',
          targetKey: target.key,
          message: `Key ${key} is generated by more than one target.`,
        });
        continue;
      }
      seen.set(key, target.key);
      keys[target.key] = key;
    } catch (error) {
      errors.push({ code: error.code ?? 'RUNTIME_KEY_INVALID', targetKey: target.key, message: error.message });
    }
  }

  return errors.length > 0 ? { ok: false, errors } : { ok: true, keys };
}
